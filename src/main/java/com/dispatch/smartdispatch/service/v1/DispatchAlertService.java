package com.dispatch.smartdispatch.service.v1;

import com.dispatch.smartdispatch.dto.v1.PlanDtos.AlertDto;
import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.util.*;

/**
 * Maintains alert identity and lifecycle between successive plan snapshots.
 * Alerts are persisted as part of the plan JSON; this service does not mutate
 * the original plan snapshot or introduce a separate alert store.
 */
@Service
public class DispatchAlertService {
    private static final String ACTIVE = "ACTIVE";
    private static final String RESOLVED = "RESOLVED";

    private final ObjectMapper objectMapper;

    public DispatchAlertService(ObjectMapper objectMapper) {
        this.objectMapper = objectMapper;
    }

    public List<AlertDto> reconcile(JsonNode previousPlanPayload,
                                    List<AlertDto> currentAlerts,
                                    LocalDate date,
                                    OffsetDateTime modelNow) {
        List<AlertDto> previousAlerts = readPreviousAlerts(previousPlanPayload);
        if (previousAlerts.isEmpty()) {
            return List.copyOf(currentAlerts);
        }

        Map<String, AlertDto> previousActiveByKey = new LinkedHashMap<>();
        Set<String> usedIds = new HashSet<>();
        int nextSequence = 0;
        for (AlertDto previous : previousAlerts) {
            if (previous.alertId() != null) {
                usedIds.add(previous.alertId());
                nextSequence = Math.max(nextSequence, sequenceOf(previous.alertId(), date));
            }
            if (isActive(previous)) {
                previousActiveByKey.put(alertKey(previous), previous);
            }
        }

        List<AlertDto> reconciled = new ArrayList<>();
        Set<String> matchedPreviousIds = new HashSet<>();

        for (AlertDto current : currentAlerts) {
            AlertDto previous = previousActiveByKey.remove(alertKey(current));
            if (previous != null) {
                reconciled.add(copy(current, previous.alertId(), previous.createdAt(), ACTIVE, null));
                if (previous.alertId() != null) {
                    matchedPreviousIds.add(previous.alertId());
                }
                continue;
            }

            AlertDto unique = current;
            if (unique.alertId() == null || usedIds.contains(unique.alertId())) {
                String nextId;
                do {
                    nextId = alertId(date, ++nextSequence);
                } while (usedIds.contains(nextId));
                unique = copy(unique, nextId, unique.createdAt(), unique.status(), unique.resolvedAt());
            }
            if (unique.alertId() != null) {
                usedIds.add(unique.alertId());
            }
            reconciled.add(unique);
        }

        // Keep the alert history in the latest plan snapshot. Active alerts that
        // are no longer generated by the current plan are closed at model_now.
        for (AlertDto previous : previousAlerts) {
            if (!isActive(previous)) {
                reconciled.add(previous);
            } else if (!matchedPreviousIds.contains(previous.alertId())) {
                reconciled.add(copy(previous, previous.alertId(), previous.createdAt(),
                        RESOLVED, modelNow));
            }
        }

        return List.copyOf(reconciled);
    }

    private List<AlertDto> readPreviousAlerts(JsonNode previousPlanPayload) {
        if (previousPlanPayload == null || previousPlanPayload.isNull()
                || !previousPlanPayload.path("alerts").isArray()) {
            return List.of();
        }
        try {
            return objectMapper.readerForListOf(AlertDto.class)
                    .without(DeserializationFeature.ADJUST_DATES_TO_CONTEXT_TIME_ZONE)
                    .readValue(previousPlanPayload.path("alerts"));
        } catch (IOException ex) {
            throw new IllegalStateException("Could not read previous plan alerts", ex);
        }
    }

    private boolean isActive(AlertDto alert) {
        return ACTIVE.equalsIgnoreCase(alert.status());
    }

    private String alertKey(AlertDto alert) {
        return String.join("|",
                Objects.toString(alert.type(), ""),
                Objects.toString(alert.orderId(), ""),
                Objects.toString(alert.groupId(), ""),
                Objects.toString(alert.staffId(), ""));
    }

    private int sequenceOf(String id, LocalDate date) {
        String prefix = "ALR-" + date.toString().replace("-", "") + "-";
        if (!id.startsWith(prefix)) {
            return 0;
        }
        try {
            return Integer.parseInt(id.substring(prefix.length()));
        } catch (NumberFormatException ignored) {
            return 0;
        }
    }

    private String alertId(LocalDate date, int sequence) {
        return "ALR-" + date.toString().replace("-", "") + "-"
                + String.format(Locale.ROOT, "%04d", sequence);
    }

    private AlertDto copy(AlertDto source, String alertId, OffsetDateTime createdAt,
                          String status, OffsetDateTime resolvedAt) {
        return new AlertDto(
                alertId,
                createdAt,
                source.type(),
                status,
                source.suggestedAction(),
                source.message(),
                resolvedAt,
                source.orderId(),
                source.groupId(),
                source.staffId(),
                source.forecastStart(),
                source.latenessMin(),
                source.suggestedStaffId(),
                source.proposedSlot(),
                source.applied()
        );
    }
}
