-- Stage C1: append-only event history for each dispatch day.
CREATE TABLE v1_dispatch_events (
    event_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_date DATE NOT NULL REFERENCES v1_dispatch_days(day_date) ON DELETE CASCADE,
    event_id VARCHAR(128) NOT NULL,
    event_type VARCHAR(40) NOT NULL CHECK (
        event_type IN (
            'NEW_ORDER',
            'ORDER_CANCELLED',
            'VISIT_DELAYED',
            'STAFF_UNAVAILABLE',
            'ORDER_TRANSFERRED'
        )
    ),
    occurred_at TIMESTAMPTZ NOT NULL,
    order_id VARCHAR(64),
    staff_id VARCHAR(64),
    target_staff_id VARCHAR(64),
    payload JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(payload) = 'object'),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_v1_dispatch_events_day_event_id UNIQUE (day_date, event_id),
    CONSTRAINT ck_v1_dispatch_events_event_id_not_blank CHECK (length(btrim(event_id)) > 0)
);

CREATE INDEX idx_v1_dispatch_events_day_sequence
    ON v1_dispatch_events (day_date, event_sequence);

CREATE INDEX idx_v1_dispatch_events_day_occurred_at
    ON v1_dispatch_events (day_date, occurred_at);
